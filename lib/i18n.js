export function normalizeLang(l) {
  return LANGS.includes(l) ? l : DEFAULT_LANG;
}

// Translator factory: const t = makeT(lang); t('nav.scrape')
export function makeT(lang) {
  const L = normalizeLang(lang);
  return (key) => dict[L][key] ?? dict[DEFAULT_LANG][key] ?? key;
}

// Locale for date/number formatting.
export function locale(lang) {
  return normalizeLang(lang) === 'en' ? 'en-US' : 'es-PY';
}

// Pick a bilingual label from a filter_schema def/option (label_en fallback label).
export function pickLabel(obj, lang) {
  if (normalizeLang(lang) === 'en' && obj.label_en) return obj.label_en;
  return obj.label;
}
